angka = int(input("masukkan angka = "))
hasil = "besar" if angka > 10 else "kecil"
print(hasil)

if hasil == "besar": # menggunakan if untuk mengecek kondisi
    print("angka lebih dari 10")
else: # menggunakan else untuk kondisi sebaliknya
    print("angka 10 atau kurang")

# Program ini mendemonstrasikan penggunaan pernyataan if-else di Python.
