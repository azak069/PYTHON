angka = (5, 2, 9, 1, 5, 6) # membuat tuple dengan beberapa angka
print(angka[0])  # Mengakses elemen pertama dari tuple
print(angka[-1]) # Mengakses elemen terakhir dari tuple
# tuple bersifat immutable, sehingga elemen tidak dapat diubah
# angka[0] = 10  # Ini akan menghasilkan error karena tuple tidak dapat diubah
print(len(angka)) # Menghitung panjang tuple

