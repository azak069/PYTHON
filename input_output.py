nama = input("Masukkan nama: ") # mengambil input nama dari pengguna
umur = input("Masukkan umur: ") # mengambil input umur dari pengguna

print("Nama Saya " + nama + ", umur " + umur) # menampilkan nama dan umur yang dimasukkan
sisa_umur = 100 - int(umur) # menghitung sisa umur dengan mengurangi umur dari 100
print("Sisa umur saya " + str(sisa_umur)) # menampilkan sisa umur dalam bentuk string

